/**
 * 議案第32号には、同じ日に審査された請願第1号の討論3件が丸ごと入っている。
 * 請願の議決文は議案と書式が違い（「〜について」が無い）、parse-bill-votes.ts が
 * 区切りとして認識できないため、請願の区間が次の議案に流れ込むのが原因。
 *
 * 会議録上、議案第32号（税条例の改正）への討論は1件も無く、3件はいずれも
 * 所得税法第56条の請願についての討論である。議会だより82号の賛否表でも
 * 税条例は16人全員が賛成しており、討論が付く議案ではない。
 * したがって議案第32号側の討論は全件を取り除き、petitions-r7-6.ts で請願側に付け替える。
 */
export function sanitizeR7_6Debates(
  votes: BillVoteRecord[]
): BillVoteRecord[] {
  return votes.map((v) =>
    v.billNumber === "議案第32号" ? { ...v, debates: [] } : v
  );
}

