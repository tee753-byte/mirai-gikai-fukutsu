/**
 * 議案第37号には、同じ日に審査された請願第2号の討論5件が丸ごと入っている。
 * 請願の議決文は議案と書式が違い（「〜について」が無い）、parse-bill-votes.ts が
 * 区切りとして認識できないため、請願の区間が次の議案に流れ込むのが原因。
 *
 * 会議録上、議案第37号への討論は1件も無い（「ないようですので、討論を終結します」）。
 * したがって議案第37号側の討論は全件を取り除き、petitions-r7-9.ts で請願側に付け替える。
 */
export function sanitizeR7_9Debates(
  votes: BillVoteRecord[]
): BillVoteRecord[] {
  return votes.map((v) =>
    v.billNumber === "議案第37号" ? { ...v, debates: [] } : v
  );
}

