describe("extractProposalReasons（言い回しの揺れ）", () => {
  // 会議録は毎回わずかに書き方が変わる。語尾が少し違うだけで見出しに当たらず、
  // 提案理由説明が黙って落ちる。ビルドもテストも通ってしまうので、
  // 実際に落ちていた形をここに残しておく（令和8年4月臨時会・6月定例会）
  it("「ご説明をいたします」（「を」が入る形）を拾う", () => {
    const text = [
      "◎市長（福井崇郎）　議案第47号及び議案第48号について一括でご説明をいたします。",
      "　まず、議案第47号令和８年度福津市一般会計補正予算（第１号）についてご説明をいたします。",
      "　今回の補正予算につきましては、保護費の追加給付等に係る経費を計上しております。",
      "　続きまして、議案第48号令和８年度福津市介護保険事業特別会計補正予算（第１号）についてご説明をいたします。",
      "　法改正に伴う介護保険システムの改修に係る経費を計上しております。",
    ].join("\n");

    const reasons = extractProposalReasons(text);

    expect(reasons.get("議案第47号")?.[0]).toContain("保護費の追加給付");
    expect(reasons.get("議案第48号")?.[0]).toContain("介護保険システムの改修");
  });

  it("「提案をします」「提案をさせていただきます」を拾う", () => {
    const text = [
      "◎議会運営委員長（戸田進一）　初めに、発議第２号福津市議会基本条例の制定について提案をします。",
      "　二元代表制の一翼を担う議会の役割を明らかにするため、議会基本条例を制定するものであります。",
      "　続きまして、発議第３号福津市議会会議規則を改正することについて提案をさせていただきます。",
      "　議会基本条例制定に伴い、整合を図るために改正を行うものであります。",
    ].join("\n");

    const reasons = extractProposalReasons(text);

    expect(reasons.get("発議第2号")?.[0]).toContain("二元代表制");
    expect(reasons.get("発議第3号")?.[0]).toContain("整合を図る");
  });

  it("件名の括弧が入れ子でも拾う", () => {
    // 承認は「…の承認について（令和７年度…補正予算（専決第３号））につきましては、」と
    // 括弧が二重になる。内側で閉じたと判定して見出しに当たらなくなっていた
    const text = [
      "◎市長（福井崇郎）　承認第２号専決処分した事件の承認について（令和７年度福津市一般会計補正予算（専決第３号））につきましては、地方譲与税等の確定額を把握し、最終的な財源の調整を行い、増額補正を行うものです。",
    ].join("\n");

    const body = extractProposalReasons(text).get("承認第2号")?.[0] ?? "";

    expect(body).toContain("最終的な財源の調整");
  });

  it("件名を読み上げない「発議第５号に関して、…提案といたします」を拾う", () => {
    // 意見書の発議は、番号だけ告げて本文を読み上げる形が多い。
    // 「…について」が無いため通常の見出しに当たらない
    const text = [
      "○議長（髙山賢二）　提出者、４番、岩下議員に提案理由の説明を求めます。岩下議員。",
      "◎４番（岩下豊）　議席番号４番、岩下豊です。",
      "　発議第５号に関して、文書を読み上げて提案といたします。",
      "　ホルムズ海峡情勢の影響から市民生活と地域経済を守るための対策を求める意見書の提出について。",
      "　上記の議案を、福津市議会会議規則第14条第１項の規定により、別紙のとおり提出いたします。",
    ].join("\n");

    const body = extractProposalReasons(text).get("発議第5号")?.[0] ?? "";

    expect(body).toContain("ホルムズ海峡情勢");
  });

  it("賛否を述べる討論は「発議第○号に…」でも見出しにしない", () => {
    const text = [
      "◎３番（山本祐平）　発議第５号ホルムズ海峡情勢の影響から市民生活と地域経済を守るための対策を求める意見書に対し、反対の立場から発言いたします。",
      "　本意見書は、国の外交方針に関わる内容を含んでおります。",
    ].join("\n");

    expect(extractProposalReasons(text).get("発議第5号")).toBeUndefined();
  });

  it("次の議案へのつなぎ言葉が末尾に残らない", () => {
    // まとめて上程された議案は「…しております。　続いて、」と続くため、
    // 次の見出しの手前で切ると接続詞だけが残り、文が途中で切れて見える
    const text = [
      "◎部長　議案第６号後期高齢者医療特別会計補正予算についてご説明します。",
      "　歳出につきましては、広域連合納付金を1,981万2,000円減額計上しております。",
      "　続きまして、議案第７号介護保険特別会計補正予算についてご説明します。",
      "　保険給付費の増加に伴う補正を主なものとしております。",
    ].join("\n");

    const body = extractProposalReasons(text).get("議案第6号")?.[0] ?? "";

    expect(body.endsWith("減額計上しております。")).toBe(true);
  });
});
