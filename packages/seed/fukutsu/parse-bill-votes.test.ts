    const report = extractPetitionReports(text).get("請願第1号") ?? "";

    expect(report).toContain("主な意見");
    expect(report).toContain("賛成多数により採択すべきものと決定した");
    // 議長の発言まで巻き込まない
    expect(report).not.toContain("質疑を受けます");
