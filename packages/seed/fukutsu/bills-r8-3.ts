export type R8_3BillVote = (typeof billVotes)[number];

/** 同意・諮問（人事案件）は討論が省略され中身がほとんど無いため、掲載対象から外す */
export function getPublishableBillVotes(): R8_3BillVote[] {
  return billVotes.filter(
    (v) => v.billNumber.startsWith("議案") || v.billNumber.startsWith("発議")
  );
}

/** 議決日。会議録の何日目で議決されたかから決める */
export function decidedAt(sessionDay: number): string {
  return DECIDED_AT[sessionDay] ?? "2026-03-26";
}
