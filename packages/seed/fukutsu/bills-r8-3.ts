/**
 * 上程日（議案が議会に出された日）。画面の日付欄は「提出」と表示されるため、
 * 議決日ではなくこちらを入れる。議決日は status_note に文章で入れている。
 * 議案第4〜45号は初日（2026-02-27）に一括上程。発議第1号は最終日に上程された。
 */
const SUBMITTED_AT_DEFAULT = "2026-02-27";
const SUBMITTED_AT: Record<string, string> = {
  発議第1号: "2026-03-26",
};

export function submittedAt(billNumber: string): string {
  return SUBMITTED_AT[billNumber] ?? SUBMITTED_AT_DEFAULT;
}

export type PlainText = {
  /** 市民向けの見出し */
  title: string;
  /** 市民向けの要約。会議録の提案理由説明をもとに平易に書き直したもの */
  summary: string;
  /**
   * やさしい版の「なぜ出されたのか」に載せる本文。
   * 議案書の理由と提案理由説明をもとに平易に書き直したもので、原文ではない。
   *
   * 上の summary と役割を分ける。summary は「何の議案か」、こちらは
   * 「なぜ必要とされたのか」と「それを誰が説明しているのか」を書く。
   * 誰の説明かを落とすと、提出者の主張をサイトの主張として読ませてしまう。
   *
   * 予算議案（議案第4〜13号）は議案書に理由欄が無く、会議録にも提案理由の
   * 説明が残っていないため、書けるだけの材料が無い。省略する。
   */
  reasonPlain?: string;
  /**
   * 理由の記録が無い議案（予算）に置く、しくみの説明。
   * 誰かの説明ではなく制度そのものの説明なので、reasonPlain とは別にする。
   */
  systemNote?: string;
  /** どの分野の議案か（タグ付けに使う） */
  tag: string;
  /** 付託された委員会 */
  committee: string | null;
};

/**
 * 公共施設の使用料を見直す議案（17件）の「なぜ出されたのか」。
 *
 * この17件は同じ「公共施設使用料設定に係る基本方針」にもとづく一括の見直しで、
 * 議案書の理由文もどれも同じ書き出しになっている。施設ごとに書き分けると
 * 説明の厚さに差が出てしまうため、共通の一文に施設名と個別の改正点だけを差し込む。
 *
 * 上の要約では「算定方法を市全体でそろえる方針」としか書いていないが、
 * 議案書には「受益者に応分の負担を求めること」も目的として並記されている。
 * 使用料が上がる理由そのものなので、ここでは省かない。
 */
function feeRevisionReason(facility: string, extra?: string): string {
  return (
    "市は、公共施設の使用料について、計算のしかたを市全体でそろえることと、" +
    "施設を使う人に使った分に応じた負担を求めることを目的に" +
    "「公共施設使用料設定に係る基本方針」をつくりました。" +
    `${facility}の使用料は、この方針にもとづいて見直すと説明しています。` +
    (extra ?? "")
  );
}

