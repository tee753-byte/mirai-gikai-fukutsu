/**
 * 令和8年3月定例会（第3回）の議案データ。
 *
 * 出どころ:
 * - 議決結果・討論・提案理由説明・委員長報告 … 会議録検索システムの会議録テキスト
 *   （fukutsu/build-bill-votes.ts で data/r8-3-bill-votes.json に書き出したもの）
 * - 議案書に印刷されている「理由」 … 市議会から提供を受けた議案書PDF
 *   （fukutsu/build-bill-documents.ts で data/r8-3-bill-documents.json に書き出したもの）
 * - やさしいタイトルと要約 … 上記の提案理由説明をもとにAIが平易に書き直したもの
 *
 * 議案書PDFそのものは再配布の可否が未確認のため、リポジトリにもサイトにも載せない。
 * 引用しているのは理由文だけ。
 *
 * 【重要】福津市議会の採決はすべて起立採決で、会議録には
 * 「賛成多数であります」としか残らない。どの議員が賛成・反対したかの氏名は
 * 会議録に一切記録されていないため、ここでは扱わない。
 * 氏名が分かるのは討論をした議員と、発議の提出者・賛成者だけ。
 */
