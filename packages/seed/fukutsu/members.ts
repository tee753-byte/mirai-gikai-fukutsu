/**
 * 福津市議会議員と会派の対応。
 *
 * 出典: 福津市議会「議会の構成」 https://www.city.fukutsu.lg.jp/gikai/kosei/2352.html
 *
 * 会議録の発言から会派を読み取る方法は取らない。議員が発言のなかで名乗るのは
 * 会派名だったり所属政党名だったりして揺れがあり（例: 会派「ミモザの会」の議員が
 * 「社会民主党」と名乗る場面がある）、掲載する情報としては会派で統一すべきため。
 */
export const MEMBER_PARTIES: Record<string, string> = {
  中村恵輔: "無所属",
  中村晶代: "公明党",
  中村清隆: "無所属",
  井手口忠信: "公明党",
  佐伯美保: "みんなの声によるみんなの会",
  倉元敏徳: "福津誠和会",
  大山隆之: "新政会",
  尾島武弘: "新政会",
  山本祐平: "無所属",
  岩下豊: "日本共産党",
  戸田進一: "日本共産党",
  榎本博: "みんなの声によるみんなの会",
  石田まなみ: "ミモザの会",
  秦浩: "福津誠和会",
  豆田優子: "ミモザの会",
};

/** 氏名から会派を引く。会議録の氏名は全角スペースが入るため取り除いてから引く */
export function findMemberParty(name: string): string | null {
  return MEMBER_PARTIES[name.replace(/[\s　]/g, "")] ?? null;
}
