/**
 * 令和7年12月定例会（第7回）の議案データ。
 *
 * 出どころ:
 * - 議決結果・討論・提案理由説明・委員長報告 … 会議録検索システムの会議録テキスト
 *   （fukutsu/build-bill-votes.ts で data/r7-12-bill-votes.json に書き出したもの）
 * - やさしいタイトルと要約 … 上記の提案理由説明をもとにAIが平易に書き直し、ユーザー確認済み
 *
 * 【注意】議案第55号・発議第8号に紐づく討論データの一部は、同日に審査された
 * 別議題（請願第4号・請願第3号）の発言を parse-bill-votes.ts が誤って拾ったもの。
 * 誤って混入した討論内容は要約に含めていない（parse-bill-votes.ts側の修正は別対応）。
 *
 * 【重要】福津市議会の採決はすべて起立採決で、会議録には
 * 「賛成多数であります」としか残らない。どの議員が賛成・反対したかの氏名は
 * 会議録に一切記録されていないため、ここでは扱わない。
 * 氏名が分かるのは討論をした議員と、発議の提出者・賛成者だけ。
 */
import { budgetSystemNote } from "./seed-bills-common";
import type { BillVoteRecord, PlainText } from "./seed-bills-common";

export const R7_12_SESSION_SLUG = "r7-12";

/**
 * 議案第55号・発議第8号は、同日に審査された別議題（請願第4号・請願第3号）の
 * 討論発言を parse-bill-votes.ts が誤って拾っている（会議録上、議案の直後に
 * 請願の討論が続いたため）。掲載前に、請願について述べている発言を取り除く
 * （議案・発議そのものへの討論は「請願」に触れない）。
 */
export function sanitizeR7_12Debates(
  votes: BillVoteRecord[]
): BillVoteRecord[] {
  return votes.map((v) => {
    if (v.billNumber !== "議案第55号" && v.billNumber !== "発議第8号") {
      return v;
    }
    return {
      ...v,
      debates: v.debates.filter((d) => !d.rawText.includes("請願")),
    };
  });
}
