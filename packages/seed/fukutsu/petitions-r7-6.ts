/**
 * 令和7年6月定例会に提出された請願のデータ。
 *
 * 請願は市民が議会に提出するもので、議会が受け取るかどうかを議決する（採択／不採択）。
 * 議案とは提出者も議決の言い方も違うが、市民から見れば「議会が何を決めたか」という点で
 * 同じなので、bills テーブルに bill_type = 'petition' として入れる。
 *
 * 出どころ:
 * - 委員長報告 … 会議録（data/r7-6-petition-reports.json）
 * - 本会議での討論 … 会議録（data/r7-6-bill-votes.json の議案第32号に紛れ込んでいる分）
 * - 議決結果と議員別の賛否 … 市議会だより82号の賛否表（seed-member-votes-r7-6.ts）
 *
 * 【重要】請願書そのもの（請願第1号.pdf）は市が公開していない資料なので、
 * 本文・請願人の氏名・住所は一切載せない。ここに載せるのは会議録と議会だよりという、
 * 市が公開している資料に書かれている内容だけ。そのため proposalReason（提案理由）は
 * null にしている（議案と違い、請願には市による提案理由説明が存在しない）。
 *
 * 【データの取り出し方】r7-9・r7-12 と違い、この会期は請願だけで日程が独立している
 * （日程第4が請願第1号、日程第5が議案第32号）。そのため委員長報告は議長の発言で
 * 塊が切れてどの議案にも入らず、build-bill-votes.ts が別ファイルに書き出している。
 * 一方で討論のほうは、請願の議決文を parse-bill-votes.ts が区切りとして認識できず
 * （「〜について」が無い）、次の議案第32号にまるごと流れ込んでいる。
 *
 * 会議録を確認したところ、議案第32号（税条例の改正）への討論は1件も無い。
 * 議会だより82号の賛否表でも税条例は16人全員が賛成しており、討論が付く議案ではない。
 * したがって議案第32号側の討論は全件が請願第1号のものであり、
 * bills-r7-6.ts の sanitizeR7_6Debates で議案側から取り除き、ここで請願側に付け替える。
 */
import petitionReports from "./data/r7-6-petition-reports.json" with {
  type: "json",
};
import type { BillVoteRecord, PlainText } from "./seed-bills-common";

/** 本会議の討論が紛れ込んでいる議案 */
const DEBATE_HOST = "議案第32号";

/**
 * 議案側に紛れ込んでいる討論を、請願側のレコードとして組み立て直す。
 * 元データを書き換えず、読み取るだけにしている。
 */
export function buildPetitionsR7_6(
  billVotes: BillVoteRecord[]
): BillVoteRecord[] {
  const debateHost = billVotes.find((v) => v.billNumber === DEBATE_HOST);
  if (!debateHost) {
    throw new Error(`請願の元になる議案が見つかりません: ${DEBATE_HOST}`);
  }

  return [
    {
      billNumber: "請願第1号",
      billName:
        "「家族従業者の働き分を経費として認めない所得税法第56条の見直しを求める意見書」提出の請願",
      outcome: "approved",
      voteMethod: "majority",
      sessionDay: debateHost.sessionDay,
      // 議案第32号への討論は会議録上1件も無いため、全件が請願第1号のもの
      debates: debateHost.debates,
      proposalReason: null,
      committeeReport:
        (petitionReports as Record<string, string>)["請願第1号"] ?? null,
      sponsors: [],
      sourceFile: debateHost.sourceFile,
    } as BillVoteRecord,
  ];
}

