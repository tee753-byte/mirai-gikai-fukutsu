/** 議決日。補正予算（議案第53〜57号）は本会②（9月1日）、それ以外は本会⑥（9月18日） */
const DECIDED_AT: Record<number, string> = {
  2: "2026-09-01",
  6: "2026-09-18",
};

export function decidedAt(sessionDay: number): string {
  return DECIDED_AT[sessionDay] ?? "2026-09-18";
}

/** 上程日。市長提出の議案等は初日（8月27日）、発議第7号は最終日に追加議案として上程 */
export function submittedAt(billNumber: string): string {
  return billNumber.startsWith("発議") ? "2026-09-18" : "2026-08-27";
}

