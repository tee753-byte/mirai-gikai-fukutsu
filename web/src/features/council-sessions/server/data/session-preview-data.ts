/**
 * 定例会の「予告」ページ用データ。
 *
 * 会期日程表・一般質問通告書・議案等一覧は、会議録や議案書の正式公開より
 * 何週間も前に市議会サイトで公開される。この一次資料だけを頼りに、開会前の
 * 段階でも会期日程・一般質問の予定・審議される議案等を案内するために使う。
 *
 * 議案の内容（提案理由や賛否）はまだ無いため、bills テーブルには入れず、
 * ここに件名だけを静的に持たせている。速報（提案理由の掲載）が始まったら
 * このセッションのデータは役目を終える。
 */

export type PreviewScheduleItem = {
  date: string;
  label: string;
  desc: string;
};

export type PreviewQuestion = {
  title: string;
  summary: string;
};

export type PreviewQuestionDay = {
  tag: string;
  date: string;
  /** date の YYYY-MM-DD 表記。今日と突き合わせて「本日の登壇者」を出すのに使う */
  isoDate: string;
  members: {
    name: string;
    questions: PreviewQuestion[];
  }[];
};

export type PreviewBillType =
  | "議案"
  | "認定"
  | "同意"
  | "報告"
  | "請願"
  | "発議";

export type PreviewBill = {
  type: PreviewBillType;
  no: string;
  title: string;
  /**
   * なぜ出されたか、を1〜2文で。議案書（提案の際に配られる資料）に書かれている
   * 範囲だけを使い、賛否・議決結果には触れない（採決前のため存在しないため）。
   * 議員個人の名前は出さない（同意人事の被任命者・請願の紹介議員・請願者も含む）。
   * 請願は請願者の氏名・住所・連絡先を一切載せない
   * （petitions-r7-6.ts と同じ方針）。趣旨・請願事項は個人が特定できる情報を
   * 含まない範囲でのみ要約する。
   * 省略時はまだ理由を書けていない（件名のみ）ことを示す。
   */
  reason?: string;
};

export type SessionPreviewData = {
  slug: string;
  asOf: string;
  headline: string;
  lead: string;
  schedule: PreviewScheduleItem[];
  questionDays: PreviewQuestionDay[];
  bills: PreviewBill[];
  sources: { label: string }[];
};

