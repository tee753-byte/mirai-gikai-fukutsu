/**
 * 今日が一般質問の登壇日なら、その日の登壇者一覧を返す。
 * トップページの「本日は開会中」バーで、その日の登壇者をその場で案内するために使う。
 */
export function getTodayQuestionDay(
  slug: string,
  todayIso: string
): PreviewQuestionDay | null {
  const preview = SESSION_PREVIEW_DATA[slug];
  if (!preview) return null;
  return preview.questionDays.find((day) => day.isoDate === todayIso) ?? null;
}

/**
 * 議案等の件数を数える。「同意」は複数人分を1件にまとめて書いているため
 * （例: no が "第5〜15号（11件）"）、その場合だけ実件数を数え直す。
 * 予告ページ・トップページのバナーの両方で同じ数え方をするため共通化する。
 */
export function countPreviewBills(bills: PreviewBill[]): number {
  return bills.reduce((total, bill) => {
    if (bill.type !== "同意") return total + 1;
    const matched = bill.no.match(/（(\d+)件）/);
    return total + (matched ? Number(matched[1]) : 1);
  }, 0);
}
