/**
 * トピックスのデータ。
 *
 * 出どころ:
 *  - 議決結果・提案理由説明・討論 … 福津市議会 会議録検索システムの会議録
 *  - 市側の答弁 … 同上（一般質問・委員会審査報告書）
 *  - 委員会での質疑応答 … 福津市議会 常任委員会審査報告書（PDF）
 *
 * 【何を取り上げるか】次のいずれかに当てはまるものを選ぶ。
 *  - 市議会の判断が分かれたもの（否決・不採択、賛否が割れた採決）
 *  - 市民の負担や暮らしに直接関わるもの（使用料、税、子育て、学校、災害）
 *  - 市が方針を変えた、または見送ったもの
 *
 * 否決・不採択のものが選ばれやすい。全議案では否決は1割程度だが、
 * トピックスでは半数を超えている。これは議決が分かれたこと自体が
 * 市民に伝わりにくいためであり、特定の立場を支持する意図はない。
 * 可決されたものにも同じ基準を当てる（福間漁港・国民健康保険税など）。
 *
 * 【何を取り上げるか】の3点は、FAQページ（`app/(main)/faq/page.tsx`）で
 * 公開している。基準を変えるときは両方を直すこと。
 * 上の否決の割合についてはFAQには書いていない。指摘を受けたときに
 * 答えられるよう、ここに残しておく。
 *
 * 【どう書くか】（CLAUDE.md の中立性・運営方針にもとづく）
 *  - 主語は「市」「市議会」。質問した議員・討論した議員を主役にしない
 *  - facts には市側の答弁と議決結果だけを書き、評価・論評は書かない
 *  - stances は議員の主張であり事実認定ではないため、賛成・反対の双方を載せる
 *  - 片側の討論しか無かった場合は、stanceNote にその事実を書く
 *    （討論が無かったことも市民が知るべき情報のため、伏せない）
 *  - 討論の発言者名は載せない（会議録で確認できる）
 *
 * このデータは会議録を人が読んで書き起こしたもので、AIによる自動抽出ではない。
 */

